//! Compile a module-integrity manifest into the verification core.
//!
//! ``scripts/build_native_license.py --attest`` writes a sha256sum-style file
//! (``<64 hex>  <path relative to the installed package>``) and points
//! ``RHETORIC_ATTEST_MANIFEST`` at it before invoking cargo. This script turns
//! that file into Rust source the core includes, so the expected digests live
//! in compiled code and cannot be edited alongside a patched module.
//!
//! With the variable unset the manifest is empty, which is what every
//! development build and `cargo test` use: nothing is enforced, and
//! ``attest`` reports ``enforced: false``.

use std::env;
use std::fs;
use std::path::PathBuf;

fn decode_digest(text: &str) -> Vec<u8> {
    assert!(
        text.len() == 64,
        "manifest digest must be 64 hex characters, got {text:?}"
    );
    (0..64)
        .step_by(2)
        .map(|index| {
            u8::from_str_radix(&text[index..index + 2], 16)
                .unwrap_or_else(|_| panic!("manifest digest is not hex: {text:?}"))
        })
        .collect()
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=RHETORIC_ATTEST_MANIFEST");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    let mut body = String::from(
        "// @generated by build.rs; do not edit.\n\
         pub static MANIFEST: &[(&str, [u8; 32])] = &[\n",
    );

    if let Ok(path) = env::var("RHETORIC_ATTEST_MANIFEST") {
        println!("cargo:rerun-if-changed={path}");
        let text = fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("cannot read attestation manifest {path}: {error}"));
        for (number, line) in text.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let mut fields = line.split_whitespace();
            let digest = fields.next().unwrap_or_default();
            let Some(relative) = fields.next() else {
                panic!("manifest line {} has no path: {line:?}", number + 1);
            };
            assert!(
                fields.next().is_none(),
                "manifest line {} has extra fields: {line:?}",
                number + 1
            );
            let bytes = decode_digest(digest);
            body.push_str(&format!(
                "    ({relative:?}, [{}]),\n",
                bytes
                    .iter()
                    .map(|byte| format!("0x{byte:02x}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
    }

    body.push_str("];\n");
    fs::write(out_dir.join("integrity_manifest.rs"), body)
        .expect("write generated integrity manifest");
}
